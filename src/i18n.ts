export function translateUi(value: string, language: Language): string {
  if (language === 'de') return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  return match[1] + (english[match[2]] ?? match[2]) + match[3];
}
